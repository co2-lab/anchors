// O CASO REAL que motivou o gate: o squash do PR entrou como "[MTUAO] Plano 0017 —
// mutação", porque o GitHub usa o TÍTULO DO PR como mensagem do squash e o título estava
// no formato do card. Esse commit — o que introduziu o plano — não apareceria no
// changelog, e ninguém notaria até a primeira versão ser gerada.
func TestAssuntoRecusaOQueSumiriaDoChangelog(t *testing.T) {
	for _, ruim := range []string{
		"[MTUAO] Plano 0017 — mutação, revisando o plano 0001",
		"ajustes",
		"feat sem os dois pontos",
		"bugfix: tipo que não existe na lista",
		"feat:sem espaço depois",
		"feat: ", // tipo certo, assunto vazio
	} {
		if subjectRE().MatchString(ruim) {
			t.Errorf("deveria recusar %q — sumiria do changelog", ruim)
		}
	}
}

// What git generates passes: nobody wrote those messages, and refusing them would break
// normal git operations (merge, revert, rebase with fixup) instead of improving the history.
func TestMessagesGitGeneratesPass(t *testing.T) {
	t.Run("CMMSC-B02: Messages git generates pass", func(t *testing.T) {})
	for _, m := range []string{
		"Merge pull request #13 from acme/feat-x",
		"Merge branch 'develop' into feat-y",
		"Revert \"feat: the thing\"",
		"fixup! feat: the thing",
		"squash! fix: another",
		"Reapply \"feat: the thing\"",
	} {
		if !generatedByGit(m) {
			t.Errorf("%q is generated by git and must not be refused", m)
		}
	}
	// A HUMAN message that starts alike does not escape: "Mergeando o trabalho" is not
	// git's, and letting it through because of the prefix would open the door to anything.
	if generatedByGit("Mergeando o trabalho da semana") {
		t.Error("only git's exact form escapes — otherwise the prefix becomes a loophole")
	}
}

// The subject is the first USEFUL line: the file git passes is full of its comments, and
// reading the raw first line would accuse every commit made through the editor.
func TestSubjectSkipsGitComments(t *testing.T) {
	t.Run("CMMSC-B01: The subject is the first line that is neither blank nor a comment", func(t *testing.T) {})
	file := "\n# Please enter the commit message for your changes.\n#\n" +
		"feat: the thing\n\n# On branch main\n"
	if got := firstUsefulLine(file); got != "feat: the thing" {
		t.Errorf("should find the subject among the comments, got %q", got)
	}
	// A message made only of comments (an aborted commit): no subject, and git refuses it.
	if got := firstUsefulLine("# all commented\n#\n"); got != "" {
		t.Errorf("with no subject it should return empty, got %q", got)
	}
}

